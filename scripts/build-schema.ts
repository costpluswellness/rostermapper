// Builds src/schema.generated.ts and docs/canonical_fields.md from schema/fields.yaml and schema/vocab.yaml.
//   node scripts/build-schema.ts          write the files
//   node scripts/build-schema.ts --check  fail if either is out of date (CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from 'yaml';
import { FILE_FIELDS } from '../src/file.ts';
import { VALUE_TYPES } from '../src/profile/value-type.ts';

const root = new URL('..', import.meta.url);
const read = (path: string) => parse(readFileSync(new URL(path, root), 'utf8'));
const out = new URL('src/schema.generated.ts', root);
const docOut = new URL('docs/canonical_fields.md', root);

const fields = read('schema/fields.yaml');
const vocab = read('schema/vocab.yaml');
validate(fields, vocab);

const ids = Object.entries(fields).flatMap(([group, entries]) => Object.keys(entries as object).map((name) => `${group}.${name}`));
const source = `// GENERATED by scripts/build-schema.ts from schema/*.yaml. Do not edit; edit the YAML and run \`pnpm schema\`.
import type { Schema } from './types';

/** Every canonical field id. */
export type FieldId =
${ids.map((id) => `\t| '${id}'`).join('\n')};

export const schema: Schema = ${JSON.stringify({ fields, vocab }, null, '\t')};
`;

const doc = dictionary(fields);

if (process.argv.includes('--check')) {
	const files: [URL, string, string][] = [[out, source, 'src/schema.generated.ts'], [docOut, doc, 'docs/canonical_fields.md']];
	const stale = files.filter(([file, text]) => readFileSync(file, 'utf8') !== text);
	if (stale.length) {
		console.error(`${stale.map(([, , name]) => name).join(' and ')} out of date. Run \`pnpm schema\`.`);
		process.exit(1);
	}
} else {
	writeFileSync(out, source);
	writeFileSync(docOut, doc);
	console.log(`${ids.length} fields → src/schema.generated.ts, docs/canonical_fields.md`);
}

// The data dictionary: one table per entity, with each field's level per action.
function dictionary(fields: Record<string, Record<string, Record<string, unknown>>>): string {
	const titles: Record<string, string> = { provider: 'Provider', practice: 'Practice location', billing: 'Billing entity', network: 'Network' };
	const cell = (s: unknown) => String(s ?? '').replace(/\|/g, '\\|');
	const level = (spec: Record<string, unknown>, action: string) =>
		((spec.required as string[]) ?? []).includes(action) ? 'R' : ((spec.preferred as string[]) ?? []).includes(action) ? 'p' : '·';
	const lines = [
		'# Canonical fields',
		'',
		'GENERATED from `schema/fields.yaml` by `pnpm schema`. Do not edit; edit the YAML and rerun.',
		'',
		'One record per roster row, every field present (empty when the file has no value). The file fields come first, then the network, provider, practice and billing fields. The CSV export adds `row` after the file fields and `issues` last.',
		'',
		'Levels per action (ADD, UPDATE, TERM): **R** required, rows missing it are flagged · **p** preferred, filled when the file has it · **·** optional.',
		'',
		'## File',
		'',
		'Set once per sheet, not mapped from columns, and written into every record. The name and sheet also name the output file: `RM_<file>_<sheet>.csv`, both with their spaces dropped (`Q3 Roster.xlsx`, sheet `LOC TERM` → `RM_Q3Roster_LOCTERM.csv`).',
		'',
		'| Field | Description | Type | Format / values |',
		'| --- | --- | --- | --- |',
		...FILE_FIELDS.map((f) => `| \`${f.id}\` | ${cell(f.description)} | ${f.type} | ${cell(f.format)} |`),
		'',
	];
	for (const [group, entries] of Object.entries(fields)) {
		lines.push(`## ${titles[group] ?? group}`, '', '| Field | Description | Type | Format / values | ADD | UPDATE | TERM |', '| --- | --- | --- | --- | :-: | :-: | :-: |');
		for (const [name, spec] of Object.entries(entries)) {
			lines.push(`| \`${group}.${name}\` | ${cell(spec.description)} | ${cell(spec.type)} | ${cell(spec.format)} | ${level(spec, 'ADD')} | ${level(spec, 'UPDATE')} | ${level(spec, 'TERM')} |`);
		}
		lines.push('');
	}
	return lines.join('\n');
}

function validate(fields: Record<string, Record<string, Record<string, unknown>>>, vocab: Record<string, unknown>) {
	const errors: string[] = [];
	const seen = new Map<string, string>();
	const key = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

	for (const [group, entries] of Object.entries(fields)) {
		for (const [name, spec] of Object.entries(entries)) {
			const id = `${group}.${name}`;
			for (const prop of Object.keys(spec)) {
				if (!['type', 'description', 'format', 'required', 'preferred', 'values', 'aliases', 'not', 'inverted', 'hidden', 'input', 'related'].includes(prop)) errors.push(`${id}: unknown key "${prop}"`);
			}
			if (!['string', 'digits', 'date', 'enum', 'boolean'].includes(spec.type as string)) errors.push(`${id}: type must be string, digits, date, enum or boolean`);
			if (typeof spec.description !== 'string' || !spec.description) errors.push(`${id}: description is required`);
			if (!Array.isArray(spec.aliases)) errors.push(`${id}: aliases must be a list`);
			for (const level of ['required', 'preferred']) {
				for (const action of (spec[level] as string[] | undefined) ?? []) {
					if (!['ADD', 'UPDATE', 'TERM'].includes(action)) errors.push(`${id}: ${level} lists unknown action "${action}"`);
				}
			}
			for (const action of (spec.preferred as string[] | undefined) ?? []) {
				if (((spec.required as string[] | undefined) ?? []).includes(action)) errors.push(`${id}: ${action} is both required and preferred`);
			}
			for (const type of (spec.values as string[] | undefined) ?? []) {
				if (!VALUE_TYPES.includes(type as never)) errors.push(`${id}: unknown value type "${type}"`);
			}
			if (spec.input && (!spec.hidden || (spec.aliases as string[])?.length || spec.required || spec.preferred)) errors.push(`${id}: an input field must be hidden, with no aliases and no required or preferred actions`);
			if (spec.related !== undefined && !Array.isArray(spec.related)) errors.push(`${id}: related must be a list`);
			// Related headers may repeat another field's alias: that's their point.
			for (const alias of [...((spec.aliases as string[]) ?? []), ...((spec.inverted as string[]) ?? [])]) {
				const other = seen.get(key(alias));
				if (other && other !== id) errors.push(`${id}: alias "${alias}" is also an alias of ${other}`);
				seen.set(key(alias), id);
			}
		}
	}
	for (const prop of ['abbreviations', 'stopwords', 'slots', 'neutral', 'qualifiers', 'ignore']) {
		if (!(prop in vocab)) errors.push(`vocab: missing "${prop}"`);
	}
	if (errors.length) {
		console.error(errors.join('\n'));
		process.exit(1);
	}
}
