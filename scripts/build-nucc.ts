// Builds src/nucc.generated.ts (taxonomy code → display name) from the NUCC taxonomy CSV.
//   node scripts/build-nucc.ts path/to/nucc_taxonomy_261.csv
// Download the CSV from https://www.nucc.org (Code Sets → Taxonomy → CSV). NUCC publishes a new
// version each January and July; rerun this when one comes out.
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';
import xlsx from 'xlsx';

const path = process.argv[2];
if (!path) throw new Error('Usage: node scripts/build-nucc.ts nucc_taxonomy_XXX.csv');
const rows = xlsx.utils.sheet_to_json<Record<string, string>>(xlsx.read(readFileSync(path, 'utf8'), { type: 'string' }).Sheets.Sheet1!);
const codes: Record<string, string> = {};
for (const r of rows) {
	const code = String(r.Code ?? '').trim();
	if (/^[0-9A-Z]{9}X$/.test(code)) codes[code] = String(r['Display Name'] || [r.Classification, r.Specialization].filter(Boolean).join(', ')).trim();
}
const version = basename(path).match(/(\d+)/)?.[1] ?? '?';
writeFileSync(new URL('../src/nucc.generated.ts', import.meta.url), `// Generated by scripts/build-nucc.ts from NUCC taxonomy v${version.replace(/(\d+)(\d)$/, '$1.$2')}. Do not edit.
// Taxonomy code → display name.
export const NUCC_VERSION = '${version.replace(/(\d+)(\d)$/, '$1.$2')}';
export const NUCC: Readonly<Record<string, string>> = ${JSON.stringify(codes, null, '\t')};
`);
console.log(`${Object.keys(codes).length} taxonomy codes → src/nucc.generated.ts`);
